def generate_header_content(name_lower: str, name_upper: str, today_str: str) -> str:
    return (HEADER_TEMPLATE
            .replace("@NAME_LOWER@", name_lower)
            .replace("@NAME_UPPER@", name_upper)
            .replace("@DATE@", today_str))

def generate_source_content(name_lower: str, name_upper: str, today_str: str) -> str:
    return (SOURCE_TEMPLATE
            .replace("@NAME_LOWER@", name_lower)
            .replace("@NAME_UPPER@", name_upper)
            .replace("@DATE@", today_str))

def update_can_parser_h(parser_h_path: Path, name_upper: str, name_lower: str, dry_run: bool):
    content = parser_h_path.read_text(encoding="utf-8")
    enum_name = f"CAN_PARSER_ID_{name_upper}"

    if enum_name in content:
        raise RuntimeError(f"Enum '{enum_name}' already exists in {parser_h_path.name}")

    pattern = r"(\s+)(CAN_PARSER_COUNT)"
    match = re.search(pattern, content)
    if not match:
        raise RuntimeError(f"Could not find CAN_PARSER_COUNT in {parser_h_path.name}")

    indent = match.group(1)
    new_enum_line = f"{indent}{enum_name},   /**< Parser Profile: {name_lower} handler */\n{indent}CAN_PARSER_COUNT"
    new_content = re.sub(pattern, new_enum_line, content, count=1)

    if not dry_run:
        parser_h_path.write_text(new_content, encoding="utf-8")

def update_can_parser_c(parser_c_path: Path, name_upper: str, name_lower: str, dry_run: bool):
    content = parser_c_path.read_text(encoding="utf-8")
    enum_name = f"CAN_PARSER_ID_{name_upper}"
    header_inc = f'#include "cp_{name_lower}.h"'
    getter_fn = f"cp_{name_lower}_profile_get"

    if header_inc in content:
        raise RuntimeError(f"Header '{header_inc}' already included in {parser_c_path.name}")
    if enum_name in content:
        raise RuntimeError(f"Enum '{enum_name}' already registered in {parser_c_path.name}")

    # 1. Add #include "cp_<name>.h"
    inc_pattern = r'(#include "cp_[a-zA-Z0-9_]+\.h"\n)(?!#include "cp_)'
    match = re.search(inc_pattern, content)
    if not match:
        inc_pattern = r'(#include "can_parser\.h"\n)'
        match = re.search(inc_pattern, content)
        if not match:
            raise RuntimeError(f"Could not find appropriate place for #include in {parser_c_path.name}")

    insert_pos = match.end()
    content = content[:insert_pos] + f'{header_inc}\n' + content[insert_pos:]

    # 2. Add entry in s_parsers array
    array_pattern = r'(static const can_profile_getter_fn s_parsers\[CAN_PARSER_COUNT\] = \{[\s\S]*?)([\t ]*)(\};)'
    match = re.search(array_pattern, content)
    if not match:
        raise RuntimeError(f"Could not find s_parsers array in {parser_c_path.name}")

    array_body = match.group(1).rstrip()
    closing_indent = match.group(2)
    new_entry = f"\n    [{enum_name}] = {getter_fn}"
    
    # Ensure previous entry has a comma if needed
    if not array_body.endswith(","):
        array_body += ","

    new_array = f"{array_body}{new_entry}\n{closing_indent}}};"
    new_content = content[:match.start()] + new_array + content[match.end():]

    if not dry_run:
        parser_c_path.write_text(new_content, encoding="utf-8")

def update_cmakelists(cmake_path: Path, name_lower: str, dry_run: bool):
    content = cmake_path.read_text(encoding="utf-8")
    source_line = f"  app/can_bus/can_parser/parsers/cp_{name_lower}.c"

    if source_line in content or f"cp_{name_lower}.c" in content:
        print_info(f"Source file already present in {cmake_path.name}")
        return

    pattern = r"(app/can_bus/can_parser/parsers/cp_[a-zA-Z0-9_]+\.c\n)"
    matches = list(re.finditer(pattern, content))
    if matches:
        last_match = matches[-1]
        insert_pos = last_match.end()
        new_content = content[:insert_pos] + f"{source_line}\n" + content[insert_pos:]
    else:
        # Fallback to after can_parser.c
        pattern = r"(app/can_bus/can_parser/can_parser\.c\n)"
        match = re.search(pattern, content)
        if not match:
            raise RuntimeError(f"Could not find target_sources section in {cmake_path.name}")
        insert_pos = match.end()
        new_content = content[:insert_pos] + f"{source_line}\n" + content[insert_pos:]

    if not dry_run:
        cmake_path.write_text(new_content, encoding="utf-8")

def main():
    if len(sys.argv) < 2 or sys.argv[1] in ("-h", "--help"):
        print(f"Usage: {sys.argv[0]} <parser_name> [--dry-run]")
        print("Example:")
        print(f"  python {sys.argv[0]} battery")
        print(f"  python {sys.argv[0]} bms_cell --dry-run")
        sys.exit(0)

    raw_name = sys.argv[1]
    dry_run = "--dry-run" in sys.argv

    try:
        name_lower, name_upper = normalize_name(raw_name)
    except ValueError as e:
        print_err(str(e))
        sys.exit(1)

    try:
        project_root = find_project_root()
    except RuntimeError as e:
        print_err(str(e))
        sys.exit(1)

    parsers_dir = project_root / "app" / "can_bus" / "can_parser" / "parsers"
    parser_h_path = project_root / "app" / "can_bus" / "can_parser" / "can_parser.h"
    parser_c_path = project_root / "app" / "can_bus" / "can_parser" / "can_parser.c"
    cmake_path = project_root / "CMakeLists.txt"

    target_h = parsers_dir / f"cp_{name_lower}.h"
    target_c = parsers_dir / f"cp_{name_lower}.c"

    # Pre-validation checks
    if target_h.exists():
        print_err(f"Header file already exists: {target_h.relative_to(project_root)}")
        sys.exit(1)

    if target_c.exists():
        print_err(f"Source file already exists: {target_c.relative_to(project_root)}")
        sys.exit(1)

    today_str = date.today().strftime("%Y-%m-%d")
    header_content = generate_header_content(name_lower, name_upper, today_str)
    source_content = generate_source_content(name_lower, name_upper, today_str)

    if dry_run:
        print_info("Dry-run mode active. No changes will be written to disk.")

    try:
        # Validate and update existing files
        update_can_parser_h(parser_h_path, name_upper, name_lower, dry_run)
        update_can_parser_c(parser_c_path, name_upper, name_lower, dry_run)
        update_cmakelists(cmake_path, name_lower, dry_run)

        # Write new files
        if not dry_run:
            parsers_dir.mkdir(parents=True, exist_ok=True)
            target_h.write_text(header_content, encoding="utf-8")
            target_c.write_text(source_content, encoding="utf-8")

    except Exception as e:
        print_err(f"Failed to generate parser: {e}")
        sys.exit(1)

    mode_label = "[DRY-RUN SUCCESS]" if dry_run else "[SUCCESS]"
    print(f"\n{mode_label} Created CAN parser profile '{name_lower}':")
    print(f"  + Created:  {target_h.relative_to(project_root)}")
    print(f"  + Created:  {target_c.relative_to(project_root)}")
    print(f"  * Updated:  {parser_h_path.relative_to(project_root)} (added CAN_PARSER_ID_{name_upper})")
    print(f"  * Updated:  {parser_c_path.relative_to(project_root)} (registered in s_parsers)")
    print(f"  * Updated:  {cmake_path.relative_to(project_root)} (added to target_sources)")
    print(f"\nNext steps:")
    print(f"  1. Edit {target_c.relative_to(project_root)}: customize CAN IDs, callbacks and filter table.")
    print(f"  2. Activate in your application:")
    print(f"     can_parser_select(&can1_inst, CAN_PARSER_ID_{name_upper});\n")

if __name__ == "__main__":
    main()

