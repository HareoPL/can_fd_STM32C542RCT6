#!/usr/bin/env python3
"""
CAN Parser Profile Generator for v-box firmware.
Automates creating new CAN parser skeletons, registering enum IDs,
updating dispatcher tables, and registering files in CMakeLists.txt.

Usage:
    python tools/create_parser.py <parser_name> [--dry-run]
"""

import sys
import os
import re
from pathlib import Path
from datetime import date

def print_err(msg: str):
    print(f"[ERROR] {msg}", file=sys.stderr)

def print_ok(msg: str):
    print(f"[OK] {msg}")

def print_info(msg: str):
    print(f"[INFO] {msg}")

def find_project_root() -> Path:
    current = Path(__file__).resolve().parent
    while current != current.parent:
        if (current / "CMakeLists.txt").exists() and (current / "app").exists():
            return current
        current = current.parent
    raise RuntimeError("Could not find project root containing CMakeLists.txt and app/ directory")

def normalize_name(raw_name: str) -> tuple:
    name = raw_name.strip()
    if name.lower().startswith("cp_"):
        name = name[3:]
    name = name.replace("-", "_")
    name_lower = name.lower()
    name_upper = name.upper()

    if not re.match(r"^[a-z][a-z0-9_]*$", name_lower):
        raise ValueError(
            f"Invalid parser name '{raw_name}'. Must be a valid C identifier (e.g. 'bms', 'battery_temp', 'j1939')."
        )
    return name_lower, name_upper

HEADER_TEMPLATE = """/**
 * @file cp_@NAME_LOWER@.h
 * @brief CAN parser profile: @NAME_LOWER@ handler.
 * @author Auto-generated by create_parser.py
 * @date @DATE@
 */

#ifndef CP_@NAME_UPPER@_H
#define CP_@NAME_UPPER@_H

#include "can_parser.h"

/**
 * @brief Returns the @NAME_LOWER@ parser profile descriptor.
 * @return Pointer to static immutable profile structure.
 */
const can_parser_profile_t *cp_@NAME_LOWER@_profile_get(void);

#endif /* CP_@NAME_UPPER@_H */
"""

